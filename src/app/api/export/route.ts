import { NextResponse, type NextRequest } from 'next/server';
import { apiUser } from '@/lib/auth/dal';
import { can } from '@/lib/config';
import { applyFilters, keywordReport, runReport } from '@/lib/domain/reports';
import type { ReportResult } from '@/lib/domain/types';
import { toCsv } from '@/lib/io/csv';
import { toXlsx } from '@/lib/io/xlsx';
import { accessError } from '@/lib/repo/access';
import { loadState } from '@/lib/repo/state';
import { V8_REPORTS } from '@/lib/repo/reports-v8';
import { audit } from '@/lib/repo/mutations-v8';
import { roleLabel } from '@/lib/config';
import { todayISO } from '@/lib/util';

export const runtime = 'nodejs';

/**
 * GET ?report=<name>[&client=&country=&stage=&division=&format=xlsx|csv]   or   ?q=<keyword request>
 * Default format is a real .xlsx workbook (Summary + Detail sheets). Permissions are checked here, on the server, for every report;
 * every export is written to the audit log (who, what, how many rows).
 */
export async function GET(req: NextRequest) {
  const ctx = await apiUser();
  if (!ctx) return NextResponse.json({ error: 'Please sign in again.' }, { status: 401 });
  { const denied = await accessError(ctx.user.role, { module: 'reports' }, 'view'); if (denied) return NextResponse.json({ error: denied }, { status: 403 }); }
  const p = req.nextUrl.searchParams, actor = { workspace: ctx.ws, role: ctx.user.role, userId: ctx.user.userId };
  const filters = { client: p.get('client') ?? 'All', country: p.get('country') ?? 'All', stage: p.get('stage') ?? 'All', today: todayISO() };
  const wanted = p.get('report') ?? '';

  let res: ReportResult;
  const v8 = V8_REPORTS[wanted];
  if (v8) {
    if (v8.permission && !can(ctx.user.role, v8.permission)) return NextResponse.json({ error: 'This report is restricted to the Managing Director and Admin Manager.' }, { status: 403 });
    const out = await v8.build(actor);
    res = { name: wanted, columns: out.columns, rows: applyFilters(out.rows, filters) };
  } else {
    const state = await loadState(ctx.ws);
    res = p.get('q') != null ? keywordReport(p.get('q') ?? '', state, ctx.user.role) : runReport(wanted, state, filters, ctx.user.role);
  }
  const division = p.get('division');
  if (division && division !== 'all') res.rows = res.rows.filter(x => x.division === division);
  if (res.error) return NextResponse.json({ error: res.error }, { status: /restricted/.test(res.error) ? 403 : 400 });
  if (!res.rows.length) return NextResponse.json({ error: `No matching records for "${res.name}". Change the filters or add records.` }, { status: 404 });

  const csv = p.get('format') === 'csv', base = res.name.replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '');
  const file = `LGM_${ctx.ws.toUpperCase()}_${base}_${todayISO()}.${csv ? 'csv' : 'xlsx'}`;
  await audit(actor, 'export', '', `Exported “${res.name}” as ${csv ? 'CSV' : 'XLSX'} — ${res.rows.length} row(s)`);
  const headers = { 'Content-Disposition': `attachment; filename="${file}"`, 'Cache-Control': 'no-store', 'X-Row-Count': String(res.rows.length) };
  if (csv) return new NextResponse('﻿' + toCsv(res.columns, res.rows), { headers: { ...headers, 'Content-Type': 'text/csv; charset=utf-8' } });
  const meta: [string, string][] = [['Report', res.name], ['Workspace', ctx.ws === 'demo' ? 'DEMO (fictional sample data)' : 'LIVE'], ['Generated', new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC'], ['Generated by', `${ctx.user.name} (${roleLabel(ctx.user.role)})`],
    ['Filters', [`Client: ${filters.client}`, `Country: ${filters.country}`, `Stage: ${filters.stage}`, division && division !== 'all' ? `Division: ${division}` : ''].filter(Boolean).join(' · ')]];
  const buf = await toXlsx({ title: `Leads Global Manpower — ${res.name}`, meta, columns: res.columns, rows: res.rows });
  return new NextResponse(new Uint8Array(buf), { headers: { ...headers, 'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' } });
}
